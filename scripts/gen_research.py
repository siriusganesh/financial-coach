"""Copy coach-reference.md Section 13 into the Edge Function as a TS module.
Run after any change to Section 13:  python3 scripts/gen_research.py
tests/test_ledger.py fails if the copy is out of date."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "supabase" / "functions" / "coach" / "research.ts"


def section13():
    ref = (ROOT / "coach" / "coach-reference.md").read_text()
    return "## 13." + ref.split("## 13.", 1)[1].split("## 14.", 1)[0].rstrip() + "\n"


def render():
    return ("// GENERATED by scripts/gen_research.py from coach/coach-reference.md Section 13.\n"
            "// Do not edit by hand.\n"
            f"export const RESEARCH = {json.dumps(section13())};\n")


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT.relative_to(ROOT)} ({len(section13())} chars)")
